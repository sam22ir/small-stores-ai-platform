#!/usr/bin/env node
// Builds the data behind the public "Wakil 500" page from the graded verdict files.
//   node scripts/stress/build-quality-data.mjs          writes apps/dashboard/src/lib/qualityData.generated.ts
//   node scripts/stress/build-quality-data.mjs --check  exits 1 when that file is out of date
// Numbers come only from the verdict files listed in docs/stress-test/rounds.json plus the case files
// (for the category of each case). Nothing in the output is typed by hand.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const STRESS = join(ROOT, "docs/stress-test");
const OUT = join(ROOT, "apps/dashboard/src/lib/qualityData.generated.ts");
export const CATEGORIES = ["ordering", "product_stock", "language", "handoff", "policies", "adversarial", "noise"];

function caseCategories() {
  const dir = join(ROOT, "scripts/stress/cases");
  const map = new Map();
  for (const f of readdirSync(dir).filter((n) => /^cases-.*\.json$/.test(n)).sort()) {
    for (const c of JSON.parse(readFileSync(join(dir, f), "utf8"))) map.set(c.id, c.category);
  }
  return map;
}

export function build() {
  const manifest = JSON.parse(readFileSync(join(STRESS, "rounds.json"), "utf8"));
  const cats = caseCategories();
  const rounds = manifest.rounds.map((r) => {
    const base = { id: r.id, date: r.date, kind: r.kind, fixes: r.fixes };
    if (r.kind !== "full") return base;
    const verdicts = JSON.parse(readFileSync(join(STRESS, r.verdicts), "utf8"));
    if (verdicts.length !== manifest.total) throw new Error(`${r.id}: ${verdicts.length} verdicts, expected ${manifest.total}`);
    const ids = new Set(verdicts.map((v) => v.id));
    if (ids.size !== verdicts.length) throw new Error(`${r.id}: duplicate ids`);
    const cls = (c) => verdicts.filter((v) => v.class === c).length;
    const pass = cls("pass");
    const sev = (s) => verdicts.filter((v) => v.class !== "pass" && v.severity === s).length;
    const categories = {};
    for (const c of CATEGORIES) categories[c] = { pass: 0, total: 0 };
    for (const v of verdicts) {
      const c = cats.get(v.id);
      if (!c || !categories[c]) throw new Error(`${r.id}: unknown category for ${v.id}`);
      categories[c].total++;
      if (v.class === "pass") categories[c].pass++;
    }
    const extra = {};
    if (r.reruns) {
      // Failures re-run twice: how many runs (out of 3, counting this round's own run) each failing case failed.
      // Only real assistant failures count (rule violations and spec gaps); script mismatches and case errors are test problems.
      const bad = (c) => c === "rule_violation" || c === "spec_gap";
      const failed = verdicts.filter((v) => bad(v.class)).map((v) => v.id);
      const runs = r.reruns.map((f) => new Map(JSON.parse(readFileSync(join(STRESS, f), "utf8")).map((x) => [x.id, x])));
      const dist = { total: failed.length, three: 0, two: 0, one: 0 };
      for (const id of failed) {
        const n = 1 + runs.reduce((a, m) => { const x = m.get(id); if (!x) throw new Error(`${r.id}: no re-run verdict for ${id}`); return a + (bad(x.new_class) ? 1 : 0); }, 0);
        dist[n === 3 ? "three" : n === 2 ? "two" : "one"]++;
      }
      dist.testProblems = verdicts.filter((v) => v.class !== "pass" && !bad(v.class)).length;
      extra.reproducibility = dist;
    }
    if (r.recheck) {
      // A stronger judge re-graded some chunks: how often it agreed, and how many of the first judge's passes it downgraded.
      const byId = new Map(verdicts.map((v) => [v.id, v]));
      let total = 0, agree = 0, firstPass = 0, downgraded = 0;
      for (const f of r.recheck) {
        for (const x of JSON.parse(readFileSync(join(STRESS, f), "utf8"))) {
          const v = byId.get(x.id);
          if (!v) throw new Error(`${r.id}: recheck id ${x.id} not in verdicts`);
          total++;
          if (x.class === v.class) agree++;
          if (v.class === "pass") { firstPass++; if (x.class !== "pass") downgraded++; }
        }
      }
      extra.recheck = { total, agree, firstPass, downgraded };
    }
    return {
      ...base, ...extra, judge: r.judge, pass, notPassed: manifest.total - pass,
      ruleViolation: cls("rule_violation"), specGap: cls("spec_gap"),
      critical: sev("critical"), high: sev("high"), categories,
    };
  });
  const data = { model: manifest.model, total: manifest.total, categories: CATEGORIES, rounds, open: manifest.open };
  return `// Generated by scripts/stress/build-quality-data.mjs from docs/stress-test/rounds.json. Do not edit by hand.\n` +
    `export const QUALITY_DATA = ${JSON.stringify(data, null, 2)} as const;\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = build();
  if (process.argv.includes("--check")) {
    const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (cur !== next) { console.error("qualityData.generated.ts is out of date: run node scripts/stress/build-quality-data.mjs"); process.exit(1); }
    console.log("quality data up to date");
  } else {
    writeFileSync(OUT, next);
    console.log("wrote", OUT);
  }
}
